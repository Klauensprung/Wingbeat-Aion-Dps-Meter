using System.Text.Json;
using AionDpsMeter.Models;
namespace AionDpsMeter.Local;
internal static class BossAlertTests
{
    internal static void Run(Action<bool,string> check){
        var tracker=new BossAlertTracker();var fight=new Fight{LocalPlayer=1};
        fight.Actors[10]=new Actor(10,"Example boss",false,false,0,"Unknown",0){NpcId=123,CapturedBoss=true};
        fight.Actors[11]=new Actor(11,"Normal mob",false,false,0,"Unknown",0){NpcId=124,CapturedBoss=false};
        NetworkEvent Event(string kind,long now,object fields)=>new(kind,now,"synthetic",JsonSerializer.SerializeToElement(fields));
        void Apply(string kind,long now,object fields)=>tracker.Apply(Event(kind,now,fields),fight);
        Apply("cast-start",1000,new {ActorId=11,SkillCode=123,CastingMs=3000});
        check(tracker.Snapshot(1000).Length==0,"Ordinary NPC casts do not trigger boss warnings");
        Apply("cast-start",1000,new {ActorId=10,SkillCode=123,CastingMs=3000,TargetId=1});
        Apply("boss-cast",1000,new {CasterId=10,SkillCode=123,CastingMs=3000,TargetId=1});
        check(tracker.Snapshot(2000) is [{State:"Casting",Duration:3000,Until:4000,TargetsYou:true}],"Boss casts retain observed timing and target without duplicate decoder warnings");
        Apply("cast-start",900,new {ActorId=10,SkillCode=456,CastingMs=5000});
        check(tracker.Snapshot(2000).Single().Skill==123,"Stale boss signals cannot replace the current cast");
        Apply("cast-stop",2500,new {ActorId=10,SkillCode=123,Result=6152});
        check(tracker.Snapshot(2600) is [{State:"Interrupted",Duration:0}]&&tracker.Snapshot(4000).Length==0,"Interrupt ends countdown and expires its short status");
        Apply("cast-start",5000,new {ActorId=10,SkillCode=456});
        check(tracker.Snapshot(5100).Single().Duration==0&&tracker.Snapshot(8000).Length==0,"Unknown cast duration has a brief untimed warning, never an invented countdown");
        Apply("telegraph",9000,new {EntityId=10,Skill=789,DurationMs=2000});
        Apply("telegraph",9500,new {EntityId=10,Skill=789,DurationMs=2000});
        check(tracker.Snapshot(10000) is [{State:"Ground attack",Until:11000}],"Repeated telegraph areas do not restart their countdown");
        Apply("actor-phase",10000,new {EntityId=10,Phase=2});Apply("boss-enrage",10100,new {EntityId=10});
        check(tracker.Snapshot(10200).Select(a=>a.State).ToHashSet().SetEquals(new[]{"Phase 2","Enrage","Ground attack"}),"Boss phase and enrage signals appear alongside area warnings");
        Apply("entity-death",10300,new {EntityId=10});Apply("cast-start",10200,new {ActorId=10,SkillCode=123,CastingMs=5000});
        check(tracker.Snapshot(10400).Length==0,"Death clears warnings and delayed earlier casts cannot revive them");
        Apply("local-zone",11000,new {MapId=1010});Apply("cast-start",10000,new {ActorId=10,SkillCode=123,CastingMs=5000});
        check(tracker.Snapshot(11100).Length==0,"Zone boundaries reject old boss casts");
        var engine=new CombatEngine();engine.Apply(new("actor",Actor:fight.Actors[10]));
        engine.Apply(new("network",Network:Event("cast-start",1000,new {ActorId=10,SkillCode=123,CastingMs=3000})));
        check(engine.BossAlerts.Snapshot(1500).Length==1,"Live engine feeds boss alerts independently of saved fight browsing");
        engine.NewFight("Next");check(engine.BossAlerts.Snapshot(1500).Length==0,"New fight clears old boss warnings");
        engine.Apply(new("network",Network:Event("cast-start",2000,new {ActorId=10,SkillCode=123,CastingMs=3000})));
        engine.Apply(new("actor",Actor:fight.Actors[10] with {NpcId=456,Name="Replacement"}));
        check(engine.BossAlerts.Snapshot(2200).Length==0,"Reused actor IDs cannot carry earlier boss alerts");
        var hpTracker=new BossAlertTracker();var hpFight=new Fight();
        hpFight.Actors[20]=new Actor(20,"Ultimate Berk",false,false,0,"Unknown",0){CapturedBoss=true};
        void Hp(long time,long? current,long? maximum=null)=>hpTracker.Apply(Event("hp",time,new {EntityId=20,CurrentHp=current,MaximumHp=maximum}),hpFight);
        Hp(100,1000,1000);Hp(200,790);Hp(300,780);
        check(hpTracker.Snapshot(300) is [{Duration:0,Detail:not null}]&&hpTracker.Snapshot(300)[0].Detail!.Contains("~75%"),"Boss name connects live HP to an untimed preparation hint three points early");
        Hp(400,800);Hp(500,760);
        check(hpTracker.Snapshot(500)[0].Started==300,"HP healing and recrossing do not repeat a phase hint");
        Hp(450,520);
        check(hpTracker.Snapshot(500)[0].Started==300,"Stale HP cannot advance phase state");
        Hp(600,530);
        check(hpTracker.Snapshot(600)[0].Detail!.Contains("~50%"),"Later HP threshold replaces earlier preparation hint");
        Hp(700,1000);
        check(hpTracker.Snapshot(700).Length==0,"Observed full-health reset clears active boss hints");
        Hp(800,780);
        check(hpTracker.Snapshot(800).Single().Started==800,"Full-health reset rearms thresholds for another pull");
        hpTracker.Clear();Hp(1000,500,1000);
        check(hpTracker.Snapshot(1000).Length==0,"Joining a boss midway does not replay past HP mechanics");
        hpTracker.Clear();Hp(1100,1000,1000);Hp(1200,200);
        check(hpTracker.Snapshot(1200).Length==0,"Large health jumps do not issue obsolete phase instructions");
        hpTracker.Clear();Hp(1300,1000);Hp(1400,780);
        check(hpTracker.Snapshot(1400).Length==0,"Unknown maximum HP cannot produce a percentage warning");
        Hp(1500,null,1000);Hp(1500,1000);Hp(1700,780);
        check(hpTracker.Snapshot(1700).Length==1,"Separate maximum HP packet supports subsequent current-only samples");
        Hp(1800,0);
        check(hpTracker.Snapshot(1800).Length==0,"Zero HP clears active preparation warnings");
        hpTracker.Clear();hpFight.Actors[20]=hpFight.Actors[20] with {CapturedBoss=false};Hp(1900,1000,1000);Hp(2000,780);
        check(hpTracker.Snapshot(2000).Length==0,"Ordinary mobs cannot trigger profiles through a matching name");
        hpFight.Actors[20]=hpFight.Actors[20] with {CapturedBoss=true};Hp(2100,1000,1000);Hp(2200,780);
        hpTracker.Apply(Event("local-zone",2300,new {MapId=1}),hpFight);Hp(2250,530);
        check(hpTracker.Snapshot(2300).Length==0,"Zone reset rejects delayed old HP warnings");
        var hpEngine=new CombatEngine();hpEngine.Apply(new("actor",Actor:hpFight.Actors[20]));
        hpEngine.Apply(new("network",Network:Event("hp",3000,new {EntityId=20,CurrentHp=1000L,MaximumHp=1000L})));
        hpEngine.Apply(new("network",Network:Event("hp",3100,new {EntityId=20,CurrentHp=780L})));
        check(hpEngine.BossAlerts.Snapshot(3100).Length==1,"Engine feeds HP alerts without rescanning retained network history");
        hpEngine.NewFight("HP next");
        check(hpEngine.BossAlerts.Snapshot(3100).Length==0,"New fight clears HP preparation state");
        hpEngine.Apply(new("network",Network:Event("hp",3200,new {EntityId=20,CurrentHp=1000L})));
        hpEngine.Apply(new("network",Network:Event("hp",3300,new {EntityId=20,CurrentHp=780L})));
        check(hpEngine.BossAlerts.Snapshot(3300).Length==1,"Retry retains maximum HP when the server only sends current health");
        hpEngine.NewFight("Mid-pull reset");
        hpEngine.Apply(new("network",Network:Event("hp",3400,new {EntityId=20,CurrentHp=530L})));
        check(hpEngine.BossAlerts.Snapshot(3400).Single().Detail!.Contains("~50%"),"DPS reset retains the current baseline for the next phase crossing");
        hpTracker.Clear();Hp(3500,970,1000);
        hpTracker.Apply(Event("cast-start",3510,new {ActorId=20,SkillCode=123,CastingMs=5000}),hpFight);
        Hp(3520,1000);
        check(hpTracker.Snapshot(3520).Length==0,"Early wipe returning from 97 percent to full health clears the old cast");
        hpTracker.Clear();Hp(3600,1000,1000);Hp(3610,780);
        Hp(3620,2000,2000);Hp(3630,1560);
        check(hpTracker.Snapshot(3630).Single().Started==3630,"A changed maximum HP rearms phase thresholds for the refreshed boss");
        var arriving=new BossAlertTracker();
        void Arrival(string kind,long time,object fields)=>arriving.Apply(Event(kind,time,fields),hpFight);
        Arrival("local-zone",4000,new {MapId=600002,AwaitingIdentity=true});
        Arrival("hp",4100,new {EntityId=20,CurrentHp=1000,MaximumHp=1000});
        Arrival("local-zone",4200,new {MapId=600002});
        Arrival("hp",4300,new {EntityId=20,CurrentHp=780});
        check(arriving.Snapshot(4300).Length==1,"Map arrival confirmation preserves freshly observed maximum HP and phase baseline");
        Arrival("cast-start",4400,new {ActorId=20,SkillCode=123,CastingMs=5000});
        Arrival("local-zone",4500,new {MapId=600002});
        check(arriving.Snapshot(4500).Any(a=>a.State=="Casting"),"Repeated map confirmation does not erase a fresh boss cast");
        Arrival("local-zone",4250,new {MapId=600012,AwaitingIdentity=true});
        check(arriving.Snapshot(4500).Any(a=>a.State=="Casting"),"Delayed older zone packet cannot erase post-teleport warnings");
        Arrival("local-zone",4600,new {MapId=600002,AwaitingIdentity=true});
        check(arriving.Snapshot(4600).Length==0,"Actual same-map teleport preparation still clears the previous encounter");
        var sceneEngine=new CombatEngine();var local=new Actor(1,"Player",true,true,0,"Cleric",1);
        sceneEngine.Apply(new("local-player",Actor:local));
        void Scene(string kind,long time,object fields)=>sceneEngine.Apply(new("network",Network:Event(kind,time,fields)));
        Scene("local-zone",5000,new {MapId=600002,AwaitingIdentity=true});
        sceneEngine.Apply(new("actor",Actor:new Actor(20,"Ultimate Berk",false,false,0,"Unknown",0){NpcId=2310171}));
        sceneEngine.Apply(new("local-player",Actor:local));
        long arrivalScene=sceneEngine.Fight.Actors[20].BossScene;
        Scene("local-zone",5100,new {MapId=600002});
        Scene("guard",5200,new {ActorId=20});
        check(sceneEngine.Fight.Actors[20].BossScene==arrivalScene&&sceneEngine.Fight.Actors[20].CapturedBoss==true,"Boss loaded during teleport remains recognized after identity and map confirmation");
        Scene("cast-start",5300,new {ActorId=20,SkillCode=123,CastingMs=3000});
        check(sceneEngine.BossAlerts.Snapshot(5400).Any(a=>a.State=="Casting"),"Fresh boss casts produce alerts after the complete teleport sequence");
        sceneEngine=new CombatEngine();sceneEngine.Apply(new("local-player",Actor:local));
        Scene("local-zone",6000,new {MapId=1010,AwaitingIdentity=true});
        sceneEngine.Apply(new("actor",Actor:new Actor(30,"Uncatalogued boss",false,false,0,"Unknown",0){NpcId=int.MaxValue}));
        sceneEngine.Apply(new("local-player",Actor:local));
        Scene("local-zone",6100,new {MapId=1010});
        Scene("guard",6200,new {ActorId=30});
        Scene("cast-start",6300,new {ActorId=30,SkillCode=123,CastingMs=3000});
        check(sceneEngine.Fight.Actors[30].CapturedBoss==true&&sceneEngine.BossAlerts.Snapshot(6400).Length==1,
            "Arrival confirmation keeps fresh NPCs eligible for live boss recognition and subsequent alerts");
        Scene("actor-position",6500,new {ActorId=30,VisibilityReason=1});
        Scene("cast-start",6600,new {ActorId=30,SkillCode=456,CastingMs=3000});
        check(sceneEngine.Fight.Actors[30].CapturedBoss==true&&sceneEngine.BossAlerts.Snapshot(6700).Single().Skill==456,
            "Visibility refresh cannot demote a boss recognized by a live guard signal in the same scene");
    }
}
